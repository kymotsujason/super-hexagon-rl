import struct
from pathlib import Path

PROJECT_DIR = Path(__file__).resolve().parents[2]
GAME_BINARY = Path.home() / ".local/share/Steam/steamapps/common/Super Hexagon/SuperHexagon"

# the strings musicclass::loadsongdata (0x476c10) splits for each track
SONG_ADDRESSES = {1: 0x55AEA8, 2: 0x565F40, 3: 0x56E7D0, 4: 0x578058, 5: 0x581870, 6: 0x58B240}


def load_segments(data):
    phoff, = struct.unpack_from("<Q", data, 0x20)
    phentsize, phnum = struct.unpack_from("<HH", data, 0x36)
    segments = []
    for i in range(phnum):
        p_type, _, p_offset, p_vaddr, _, p_filesz, _, _ = struct.unpack_from("<IIQQQQQQ", data, phoff + i * phentsize)
        if p_type == 1:
            segments.append((p_vaddr, p_offset, p_filesz))
    return segments


def read_c_string(data, segments, address):
    for vaddr, offset, size in segments:
        if vaddr <= address < vaddr + size:
            start = offset + (address - vaddr)
            end = data.index(b"\0", start)
            return data[start:end]
    raise ValueError(f"address {address:#x} isn't in a loaded segment")


def main():
    data = GAME_BINARY.read_bytes()
    segments = load_segments(data)
    lines = ["/* generated by sim/tools/extract_songdata.py from the game binary, don't edit */",
             "const char *const shxSongData[7] = {", "\t0,"]
    for track in range(1, 7):
        text = read_c_string(data, segments, SONG_ADDRESSES[track]).decode("ascii")
        escaped = text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\r", "\\r")
        lines.append(f'\t"{escaped}",')
        print(f"track {track}: {len(text)} characters, {text.count(',') + 1} fields")
    lines.append("};")
    out = PROJECT_DIR / "sim" / "gen" / "songdata.c"
    out.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
